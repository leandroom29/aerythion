"""
evaluation.py
-------------
Machine-learning model evaluation module for the project.
"""

import pandas as pd
from sklearn.metrics import (
    mean_absolute_error,
    r2_score,
    root_mean_squared_error
)

# REGRESSION EVALUATION

def evaluate_regression(y_true, y_pred) -> dict:
    """
    Calculate standard metrics for regression models.

    """
    rmse = root_mean_squared_error(y_true, y_pred)
    mae = mean_absolute_error(y_true, y_pred)
    r2 = r2_score(y_true, y_pred)

    return {
        "RMSE": rmse,
        "MAE": mae,
        "R2": r2
    }


# ANOMALY DETECTION EVALUATION

def summarize_anomalies(df: pd.DataFrame, column: str = "anomaly") -> dict:
    """
    Summarize the anomaly detection results.

    """
    total = len(df)
    anomalies = (df[column] == -1).sum()
    normal = (df[column] == 1).sum()

    return {
        "total_samples": total,
        "normal_points": int(normal),
        "anomalies_detected": int(anomalies),
        "anomaly_ratio": anomalies / total if total > 0 else 0
    }


# CLUSTERING EVALUATION

def summarize_clusters(df: pd.DataFrame, column: str = "cluster") -> dict:
    """
    Summarize the distribution of clusters generated by K-Means.

    """
    return df[column].value_counts().sort_index().to_dict()